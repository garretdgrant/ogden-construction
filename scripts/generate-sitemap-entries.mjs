import { execFileSync } from "node:child_process";
import { promises as fs } from "node:fs";
import path from "node:path";

const root = process.cwd();
const appDirectory = "src/app";
const outputFile = "src/app/sitemap.generated.ts";
const excludedPaths = new Set(["/contact/thank-you"]);

const staticSourceFiles = {
  "/": ["src/lib/ogden-homepage.data.ts"],
  "/services": ["src/app/services/data/services.ts"],
  "/locations-we-serve": ["src/lib/locations-data.ts"],
};

const toPosixPath = (value) => value.split(path.sep).join("/");

const walkPageFiles = async (directory) => {
  const entries = await fs.readdir(path.join(root, directory), {
    withFileTypes: true,
  });
  const pageFiles = [];

  for (const entry of entries) {
    const relativePath = toPosixPath(path.join(directory, entry.name));

    if (entry.isDirectory()) {
      if (entry.name === "api") continue;
      pageFiles.push(...(await walkPageFiles(relativePath)));
    } else if (entry.name === "page.tsx") {
      pageFiles.push(relativePath);
    }
  }

  return pageFiles;
};

const routeFromPageFile = (pageFile) => {
  const segment = pageFile
    .replace(new RegExp(`^${appDirectory}/?`), "")
    .replace(/\/?page\.tsx$/, "");

  return segment ? `/${segment}` : "/";
};

const readSource = (sourceFile) =>
  fs.readFile(path.join(root, sourceFile), "utf8");

const discoverServiceEntries = async () => {
  const dataFile = "src/app/services/data/services.ts";
  const source = await readSource(dataFile);
  const slugs = [...source.matchAll(/^\s{4}slug:\s*["']([^"']+)["']/gm)].map(
    (match) => match[1],
  );

  return slugs.map((slug) => ({
    path: `/services/${slug}`,
    sourceFiles: ["src/app/services/[slug]/page.tsx", dataFile],
    changeFrequency: "monthly",
    priority: 0.8,
  }));
};

const discoverLocationEntries = async () => {
  const dataFile = "src/lib/locations-data.ts";
  const source = await readSource(dataFile);
  const slugs = [...source.matchAll(/pageSlug:\s*["']([^"']+)["']/g)].map(
    (match) => match[1],
  );

  return slugs.map((slug) => ({
    path: `/locations-we-serve/${slug}`,
    sourceFiles: [`src/app/locations-we-serve/${slug}/page.tsx`, dataFile],
    changeFrequency: "monthly",
    priority: 0.8,
  }));
};

const getExplicitDateModified = async (sourceFiles) => {
  for (const sourceFile of sourceFiles) {
    try {
      const source = await readSource(sourceFile);
      const match = source.match(/dateModified:\s*["'](\d{4}-\d{2}-\d{2})["']/);

      if (match) return match[1];
    } catch {
      // A missing optional source is handled by the git fallback below.
    }
  }

  return undefined;
};

const hasUncommittedSourceChanges = (sourceFiles) => {
  try {
    return Boolean(
      execFileSync("git", ["status", "--porcelain", "--", ...sourceFiles], {
        cwd: root,
        encoding: "utf8",
      }).trim(),
    );
  } catch {
    return true;
  }
};

const getGitLastModified = (sourceFiles) => {
  if (hasUncommittedSourceChanges(sourceFiles)) return undefined;

  try {
    const result = execFileSync(
      "git",
      ["log", "-1", "--format=%cI", "--", ...sourceFiles],
      {
        cwd: root,
        encoding: "utf8",
      },
    ).trim();

    return result ? result.slice(0, 10) : undefined;
  } catch {
    return undefined;
  }
};

const addLastModified = async (entry) => {
  const explicitDate = await getExplicitDateModified(entry.sourceFiles);
  const lastModified = explicitDate ?? getGitLastModified(entry.sourceFiles);

  return {
    path: entry.path,
    ...(lastModified ? { lastModified } : {}),
    changeFrequency: entry.changeFrequency,
    priority: entry.priority,
  };
};

const pageFiles = await walkPageFiles(appDirectory);
const staticEntries = pageFiles
  .filter((pageFile) => !pageFile.includes("["))
  .map((pageFile) => {
    const routePath = routeFromPageFile(pageFile);

    return {
      path: routePath,
      sourceFiles: [pageFile, ...(staticSourceFiles[routePath] ?? [])],
      changeFrequency: "monthly",
      priority: routePath === "/" ? 1 : 0.7,
    };
  })
  .filter((entry) => !excludedPaths.has(entry.path));

const entries = [
  ...staticEntries,
  ...(await discoverServiceEntries()),
  ...(await discoverLocationEntries()),
];

const uniqueEntries = [
  ...new Map(entries.map((entry) => [entry.path, entry])).values(),
].sort((a, b) => {
  if (a.path === "/") return -1;
  if (b.path === "/") return 1;
  return a.path.localeCompare(b.path);
});

const generatedEntries = await Promise.all(uniqueEntries.map(addLastModified));
const output = `// Generated by scripts/generate-sitemap-entries.mjs. Do not edit manually.\n\nexport type GeneratedSitemapEntry = {\n  path: string;\n  lastModified?: string;\n  changeFrequency: \"monthly\";\n  priority: number;\n};\n\nexport const generatedSitemapEntries: GeneratedSitemapEntry[] = ${JSON.stringify(generatedEntries, null, 2)};\n`;

await fs.writeFile(path.join(root, outputFile), output, "utf8");
console.log(
  `[sitemap] Generated ${generatedEntries.length} entries at ${outputFile}`,
);
